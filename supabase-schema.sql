create table public.forum_posts (
  id bigint generated by default as identity primary key,
  author text not null check (char_length(trim(author)) between 1 and 30),
  title text not null check (char_length(trim(title)) between 1 and 80),
  content text not null check (char_length(trim(content)) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.forum_posts enable row level security;

grant select on public.forum_posts to anon, authenticated;
grant insert on public.forum_posts to anon, authenticated;
grant usage, select on sequence public.forum_posts_id_seq to anon, authenticated;

create policy "Anyone can read forum posts"
on public.forum_posts
for select
to anon, authenticated
using (true);

create policy "Anyone can create forum posts"
on public.forum_posts
for insert
to anon, authenticated
with check (true);

create index forum_posts_created_at_idx
on public.forum_posts (created_at desc);

create table public.forum_replies (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.forum_posts(id) on delete cascade,
  author text not null check (char_length(trim(author)) between 1 and 30),
  content text not null check (char_length(trim(content)) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.forum_replies enable row level security;

grant select on public.forum_replies to anon, authenticated;
grant insert on public.forum_replies to anon, authenticated;
grant usage, select on sequence public.forum_replies_id_seq to anon, authenticated;

create policy "Anyone can read forum replies"
on public.forum_replies
for select
to anon, authenticated
using (true);

create policy "Anyone can create forum replies"
on public.forum_replies
for insert
to anon, authenticated
with check (true);

create index forum_replies_post_id_created_at_idx
on public.forum_replies (post_id, created_at);

-- Run this migration after the original forum policies have been created.
drop policy if exists "Anyone can create forum posts" on public.forum_posts;
drop policy if exists "Anyone can create forum replies" on public.forum_replies;

revoke insert on public.forum_posts from anon;
revoke insert on public.forum_replies from anon;

create policy "Authenticated users can create forum posts"
on public.forum_posts
for insert
to authenticated
with check (true);

create policy "Authenticated users can create forum replies"
on public.forum_replies
for insert
to authenticated
with check (true);
